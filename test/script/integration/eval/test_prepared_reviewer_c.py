def test_main_generates_missing_directories_and_check_reports_missing(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, artifacts: dict[str, bytes]
) -> None:
    # Given fresh output directories and the deterministic public artifacts.
    monkeypatch.setattr(prepare_c, "INPUTS", tmp_path)
    monkeypatch.setattr(prepare_c, "prepare", lambda: artifacts)
    monkeypatch.setattr("sys.argv", ["prepare_c", "--check"])
    # When checking before generation.
    with pytest.raises(SystemExit, match="C artifacts differ"):
        prepare_c.main()
    # Then the check reports a mismatch without creating directories.
    assert not (tmp_path / "c-rules").exists()
    assert not (tmp_path / "c-functions").exists()
    # When generating into the fresh location and then checking.
    monkeypatch.setattr("sys.argv", ["prepare_c"])
    prepare_c.main()
    monkeypatch.setattr("sys.argv", ["prepare_c", "--check"])
    prepare_c.main()
    # Then both selected directories contain the expected public files.
    assert len(list((tmp_path / "c-rules").iterdir())) == 3
    assert len(list((tmp_path / "c-functions").iterdir())) == 62
    # When a generated directory is subsequently removed.
    shutil.rmtree(tmp_path / "c-functions")
    # Then checking reports the missing artifacts and does not recreate it.
    with pytest.raises(SystemExit, match="C artifacts differ"):
        prepare_c.main()
    assert not (tmp_path / "c-functions").exists()


